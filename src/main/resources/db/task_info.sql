-- 任务基本信息表
CREATE TABLE IF NOT EXISTS `task_info` (
  `id` VARCHAR(50) NOT NULL COMMENT '主键ID',
  `org_id` VARCHAR(50) DEFAULT NULL COMMENT '组织ID',
  `create_by` VARCHAR(50) DEFAULT NULL COMMENT '创建人',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `task_title` VARCHAR(50) DEFAULT NULL COMMENT '任务标题',
  `sheet_code` VARCHAR(50) DEFAULT NULL COMMENT '任务编号',
  `task_desc` VARCHAR(400) DEFAULT NULL COMMENT '任务描述',
  `start_time` DATETIME DEFAULT NULL COMMENT '需求开始时间',
  `end_time` DATETIME DEFAULT NULL COMMENT '需求结束时间',
  `processer_id` VARCHAR(50) DEFAULT NULL COMMENT '处理人账户',
  `processer_name` VARCHAR(20) DEFAULT NULL COMMENT '处理人姓名',
  `area_code` VARCHAR(20) DEFAULT NULL COMMENT '地点代码',
  `area_name` VARCHAR(50) DEFAULT NULL COMMENT '地点名称',
  `finish_time` DATETIME DEFAULT NULL COMMENT '实际完成时间',
  `audit_flag` INT DEFAULT NULL COMMENT '审批标志',
  `urgent_level` VARCHAR(100) DEFAULT NULL COMMENT '紧急程度',
  `task_level` VARCHAR(20) DEFAULT NULL COMMENT '任务级别',
  `task_evaluation` VARCHAR(20) DEFAULT NULL COMMENT '任务评价',
  `task_importance_level` VARCHAR(20) DEFAULT NULL COMMENT '重要程度',
  `task_difficulty_level` VARCHAR(20) DEFAULT NULL COMMENT '难易程度',
  `parent_code` VARCHAR(20) DEFAULT NULL COMMENT '父级任务',
  `task_sort` INT DEFAULT 1 COMMENT '任务父子级别',
  `task_status` VARCHAR(50) DEFAULT 'CREATED' COMMENT '任务状态',
  `task_plan_hour` DOUBLE(10,2) DEFAULT NULL COMMENT '任务计划工时',
  `task_real_hour` DOUBLE(10,2) DEFAULT NULL COMMENT '任务实际工时',
  `task_type` VARCHAR(20) DEFAULT NULL COMMENT '任务分类',
  `task_callback_url` VARCHAR(20) DEFAULT NULL COMMENT '回调URL',
  `task_callback_code` VARCHAR(20) DEFAULT NULL COMMENT '回调单据号',
  `expire_status` INT DEFAULT NULL COMMENT '是否过期',
  `file_info` VARCHAR(500) DEFAULT NULL COMMENT '文件JSON字符串',
  `remind_type` VARCHAR(200) DEFAULT NULL COMMENT '提醒方式',
  `participant` TEXT DEFAULT NULL COMMENT '参与人',
  `sheet_type_id` VARCHAR(50) DEFAULT '50' COMMENT '编码规则id',
  `keywords` VARCHAR(200) DEFAULT NULL COMMENT '关键字',
  `sheet_id` VARCHAR(50) DEFAULT NULL COMMENT '单据ID',
  `task_class` VARCHAR(50) DEFAULT NULL COMMENT '待办或通知',
  `business_type` VARCHAR(50) DEFAULT NULL COMMENT '业务类型',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_sheet_code` (`sheet_code`),
  KEY `idx_org_id` (`org_id`),
  KEY `idx_processer_id` (`processer_id`),
  KEY `idx_task_status` (`task_status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='任务基本信息表';
